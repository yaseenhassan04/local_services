<script>
    if (typeof AOS !== 'undefined') {
        AOS.init({
            duration: 800,
            offset: 100,
            easing: 'ease-out-cubic',
            once: true
        });
    }

    // كود الجافاسكريبت للتحكم في استجابة الفوتر مع الـ Sidebar
    document.addEventListener("DOMContentLoaded", function() {
        const sidebarToggle = document.getElementById("sidebarToggle");
        const appSidebar = document.getElementById("appSidebar");
        const appFooter = document.querySelector(".kh-footer");

        // دالة لضبط الهوامش حسب حالة الشاشة والـ Sidebar للـ Layout المعتمد للموقع
        function adjustFooter() {
            if (!appFooter) return;
            if (window.innerWidth <= 768) {
                appFooter.style.marginRight = "0";
            } else {
                if (appSidebar && (appSidebar.classList.contains("collapsed") || appSidebar.classList.contains("close"))) {
                    appFooter.style.marginRight = "0";
                } else {
                    appFooter.style.marginRight = "var(--sidebar-width, 260px)";
                }
            }
        }

        if (sidebarToggle && appSidebar && appFooter) {
            sidebarToggle.addEventListener("click", function() {
                // مهلة زمنية صغيرة لمزامنة الإزاحة مع أنميشن الإغلاق للـ CSS
                setTimeout(adjustFooter, 50);
            });
        }

        // تشغيل الفحص مباشرة وعقبه أي عملية تغيير لحجم المتصفح لضمان ثبات الهيكل الداخلي
        adjustFooter();
        window.addEventListener("resize", adjustFooter);

        // الاستماع للتغييرات الفجائية للـ Classes على عنصر السايدبار للتكيف الفوري
        if (appSidebar) {
            const observer = new MutationObserver(adjustFooter);
            observer.observe(appSidebar, {
                attributes: true,
                attributeFilter: ['class']
            });
        }
    });
</script>
